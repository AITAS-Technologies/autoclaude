import { afterAll, describe, expect, it } from "vitest";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { ConfigError, loadProjectConfig } from "../../src/config/load.js";
import { CODE_REVIEW_ANGLES, EFFORTS, LOCAL_OVERRIDABLE } from "../../src/config/types.js";

const FIXTURES = resolve(import.meta.dirname, "../fixtures/projects");
const tmpDirs: string[] = [];
afterAll(() => {
  for (const d of tmpDirs) rmSync(d, { recursive: true, force: true });
});

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Json = Record<string, any>;

const readFixture = (name: string): Json =>
  JSON.parse(readFileSync(join(FIXTURES, name, ".autoclaude", "config.json"), "utf8"));

/** A project in a temp dir: the minimal fixture with `edit` applied, plus an optional local file. */
function project(edit?: (c: Json) => void, local?: Json | string): string {
  const dir = mkdtempSync(join(tmpdir(), "ac-config-"));
  tmpDirs.push(dir);
  const cfg = readFixture("minimal");
  edit?.(cfg);
  mkdirSync(join(dir, ".autoclaude"));
  writeFileSync(join(dir, ".autoclaude", "config.json"), JSON.stringify(cfg, null, 2));
  if (local !== undefined) {
    const text = typeof local === "string" ? local : JSON.stringify(local);
    writeFileSync(join(dir, ".autoclaude", "config.local.json"), text);
  }
  return dir;
}

describe("loadProjectConfig, the contract", () => {
  const cfg = loadProjectConfig(join(FIXTURES, "minimal"));

  it("loads the minimal fixture", () => {
    expect(cfg.branches).toEqual({ integration: "develop", production: "main" });
  });

  it("defaults the remote to origin and the worktree root to .autoclaude/worktrees", () => {
    expect(cfg.forge.remote).toBe("origin");
    expect(cfg.worktrees).toEqual({ root: ".autoclaude/worktrees", copy: [] });
  });

  it("applies the other defaults", () => {
    expect(cfg.stages.codeReview.parallel).toBe(4);
    expect(cfg.caps.maxTurnsPerStage).toBe(200);
    expect(cfg.branchPrefix).toBe("agent/");
    expect(cfg.messages).toEqual({ footer: "Generated by autoclaude", defuseMentions: true });
    expect(cfg.stages.triage.effort).toBe("medium");
    expect(cfg.codeReview.angles).toEqual([...CODE_REVIEW_ANGLES]);
    expect(cfg.fence).toEqual({ allow: [] });
  });

  it("names an integration and a production branch, and they differ", () => {
    expect(cfg.branches.integration.length).toBeGreaterThan(0);
    expect(cfg.branches.integration).not.toBe(cfg.branches.production);
  });

  it("gives every label a non-empty name, all distinct", () => {
    const values = [...Object.values(cfg.labels), cfg.queue.ready];
    for (const v of values) expect(v.trim().length).toBeGreaterThan(0);
    expect(new Set(values).size).toBe(values.length);
  });

  it("gives every cap a usable number; a concurrency may be zero", () => {
    const { concurrency, ...rest } = cfg.caps;
    for (const [name, value] of Object.entries(rest)) {
      expect(Number.isInteger(value), `caps.${name}`).toBe(true);
      expect(value, `caps.${name}`).toBeGreaterThanOrEqual(1);
    }
    for (const value of Object.values(concurrency)) expect(value).toBeGreaterThanOrEqual(0);
  });

  it("knows nine code review angles, four efforts and four personal keys", () => {
    expect(CODE_REVIEW_ANGLES).toHaveLength(9);
    expect(EFFORTS).toEqual(["low", "medium", "high", "max"]);
    expect(LOCAL_OVERRIDABLE).toEqual(["budget", "schedule", "humans", "stages"]);
  });

  it("loads the full fixture with its personal overrides merged", () => {
    const full = loadProjectConfig(join(FIXTURES, "full"));
    expect(full.humans).toEqual(["maintainer-b"]);
    expect(full.budget?.claude).toEqual({ fiveHourPct: 50, weeklyPct: 60 });
    expect(full.budget?.codex).toEqual({ fiveHourPct: 70, weeklyPct: 85 });
    expect(full.schedule.profiles.nightStopsTakingWorkAt).toBe("04:30");
    expect(full.schedule.profiles.day).toEqual({ from: "08:00", to: "20:00" });
    expect(full.stages.plan.model).toBe("model-local");
    expect(full.stages.plan.effort).toBe("max");
    expect(full.stages.plan.fallback?.runtime).toBe("codex");
    expect(full.forge.remote).toBe("upstream");
    expect(full.stages.codeReview.parallel).toBe(3);
  });

  it("refuses a project with no .autoclaude/config.json, naming the file", () => {
    const dir = mkdtempSync(join(tmpdir(), "ac-config-"));
    tmpDirs.push(dir);
    expect(() => loadProjectConfig(dir)).toThrow(/config\.json: cannot read/);
    expect(() => loadProjectConfig(dir)).toThrow(ConfigError);
  });

  it("loads from a copied project directory", () => {
    const dir = mkdtempSync(join(tmpdir(), "ac-config-"));
    tmpDirs.push(dir);
    cpSync(join(FIXTURES, "full"), dir, { recursive: true });
    expect(loadProjectConfig(dir).humans).toEqual(["maintainer-b"]);
  });
});

describe("files saved by a Windows editor", () => {
  it("loads config.json with BOM and CRLF", () => {
    const dir = project();
    const file = join(dir, ".autoclaude", "config.json");
    const text = readFileSync(file, "utf8");
    writeFileSync(file, "﻿" + text.replace(/\n/g, "\r\n"));
    expect(loadProjectConfig(dir).branches.integration).toBe("develop");
  });

  it("loads config.local.json with BOM and CRLF", () => {
    const local = JSON.stringify({ humans: ["someone"] }, null, 2).replace(/\n/g, "\r\n");
    const dir = project(undefined, "﻿" + local);
    expect(loadProjectConfig(dir).humans).toEqual(["someone"]);
  });

  it("names the file on a JSON syntax error", () => {
    const dir = project(undefined, "{ not json");
    expect(() => loadProjectConfig(dir)).toThrow(/config\.local\.json: invalid JSON/);
  });
});

describe("config.local.json", () => {
  it("lets config.local.json override budget, schedule, humans and a stage's model", () => {
    const dir = project(undefined, {
      budget: { claude: { fiveHourPct: 10, weeklyPct: 20 } },
      schedule: { timezone: "Europe/Berlin" },
      humans: ["me"],
      stages: { implement: { model: "model-mine", effort: "low" } },
    });
    const c = loadProjectConfig(dir);
    expect(c.budget).toEqual({ claude: { fiveHourPct: 10, weeklyPct: 20 } });
    expect(c.schedule.timezone).toBe("Europe/Berlin");
    expect(c.schedule.profiles.day.from).toBe("08:00");
    expect(c.humans).toEqual(["me"]);
    expect(c.stages.implement).toMatchObject({
      runtime: "claude",
      model: "model-mine",
      effort: "low",
    });
  });

  it("refuses gates in config.local.json, naming the key", () => {
    const dir = project(undefined, { gates: [] });
    expect(() => loadProjectConfig(dir)).toThrow(
      /config\.local\.json: gates is not a personal setting/,
    );
    expect(() => loadProjectConfig(dir)).toThrow(ConfigError);
  });

  it("refuses a stage setting that is not runtime, model, effort or fallback", () => {
    const dir = project(undefined, { stages: { codeReview: { parallel: 8 } } });
    expect(() => loadProjectConfig(dir)).toThrow(
      /config\.local\.json: stages\.codeReview\.parallel is not a personal setting/,
    );
  });

  it("refuses a new stage key", () => {
    const dir = project(undefined, { stages: { deploy: { model: "x" } } });
    expect(() => loadProjectConfig(dir)).toThrow(/config\.local\.json: stages\.deploy/);
  });

  it("refuses an extra key on a stage spec", () => {
    const dir = project(undefined, { stages: { plan: { maxTurns: 3 } } });
    expect(() => loadProjectConfig(dir)).toThrow(
      /config\.local\.json: stages\.plan\.maxTurns is not a personal setting/,
    );
  });

  it("refuses a nested spec that config.json does not have", () => {
    const dir = project(undefined, { stages: { implement: { escalated: { model: "x" } } } });
    expect(() => loadProjectConfig(dir)).toThrow(
      /config\.local\.json: stages\.implement\.escalated/,
    );
  });

  it("overrides a nested spec that exists", () => {
    const dir = project(undefined, {
      stages: {
        planReview: { scorer: { model: "scorer-mine" } },
        codeReview: { scorer: { effort: "high" }, angles: { default: { model: "angle-mine" } } },
      },
    });
    const c = loadProjectConfig(dir);
    expect(c.stages.planReview.scorer.model).toBe("scorer-mine");
    expect(c.stages.codeReview.scorer.effort).toBe("high");
    expect(c.stages.codeReview.angles.default.model).toBe("angle-mine");
  });

  it("names config.local.json when a personal value is malformed", () => {
    const dir = project(undefined, { schedule: { profiles: { day: { from: "8am" } } } });
    expect(() => loadProjectConfig(dir)).toThrow(
      /config\.local\.json: schedule\.profiles\.day\.from must be HH:MM/,
    );
  });
});

describe("refusals in config.json", () => {
  const refuses = (edit: (c: Json) => void, pattern: RegExp) =>
    expect(() => loadProjectConfig(project(edit))).toThrow(pattern);

  it("refuses an unknown top-level key, naming it", () => {
    refuses((c) => (c.triggers = { ui: [] }), /config\.json: unknown key "triggers"/);
  });

  it("refuses an unknown nested key, naming the dotted path", () => {
    refuses((c) => (c.caps.fixRound = 3), /unknown key "caps\.fixRound"/);
  });

  it("refuses a config missing a required key, and says which", () => {
    refuses((c) => delete c.branches, /config\.json: missing required key "branches"/);
  });

  it("refuses a stage with an unknown runtime", () => {
    refuses((c) => (c.stages.plan.runtime = "gpt"), /stages\.plan\.runtime/);
  });

  it("refuses an effort that is not one of the four", () => {
    refuses(
      (c) => (c.stages.codeReview.scorer.effort = "extreme"),
      /stages\.codeReview\.scorer\.effort must be one of low, medium, high, max/,
    );
  });

  it("refuses an empty model", () => {
    refuses((c) => (c.stages.implement.model = " "), /stages\.implement\.model must name a model/);
  });

  it("refuses an unknown code review angle and lists the known ones", () => {
    const edit = (c: Json) => (c.codeReview = { angles: ["bugs", "vibes"], scoreThreshold: 7 });
    refuses(edit, /codeReview\.angles has an unknown angle/);
    refuses(edit, /criteria/);
  });

  it("refuses a repeated angle and an empty angle list", () => {
    refuses(
      (c) => (c.codeReview = { angles: ["bugs", "bugs"], scoreThreshold: 7 }),
      /repeats an angle/,
    );
    refuses(
      (c) => (c.codeReview = { angles: [], scoreThreshold: 7 }),
      /codeReview\.angles must list at least one angle/,
    );
  });

  it("refuses an unknown angle key in the stage map", () => {
    refuses(
      (c) => (c.stages.codeReview.angles.vibes = { runtime: "claude", model: "m" }),
      /stages\.codeReview\.angles has an unknown angle key/,
    );
  });

  it("refuses an angle map without a default", () => {
    refuses(
      (c) => (c.stages.codeReview.angles = { bugs: { runtime: "claude", model: "m" } }),
      /stages\.codeReview\.angles\.default is missing/,
    );
  });

  it("refuses a null angle spec by name instead of crashing", () => {
    refuses(
      (c) => (c.stages.codeReview.angles.bugs = null),
      /stages\.codeReview\.angles\.bugs must be an object but is null/,
    );
  });

  it("refuses thresholds outside 1-10", () => {
    refuses(
      (c) => (c.codeReview = { angles: ["bugs"], scoreThreshold: 11 }),
      /codeReview\.scoreThreshold must be an integer from 1 to 10/,
    );
    refuses(
      (c) => (c.planReview = { scoreThreshold: 0 }),
      /planReview\.scoreThreshold must be an integer from 1 to 10/,
    );
  });

  it("refuses a malformed time and names the key", () => {
    refuses(
      (c) => (c.schedule.profiles.day.from = "8am"),
      /schedule\.profiles\.day\.from must be HH:MM/,
    );
  });

  it("refuses an absent cap and an empty check list", () => {
    refuses(
      (c) => delete c.caps.staleClaimHours,
      /caps\.staleClaimHours must be a whole number of at least 1/,
    );
    refuses((c) => (c.requiredChecks = []), /requiredChecks must be a non-empty list/);
  });

  it("refuses colliding labels", () => {
    refuses((c) => (c.labels.blocked = "agent-working"), /labels\.blocked repeats/);
  });

  it("refuses identical integration and production branches", () => {
    refuses((c) => (c.branches.production = "develop"), /branches\.production must differ/);
  });

  it("refuses a branch prefix without a trailing slash", () => {
    refuses(
      (c) => (c.branchPrefix = "Agent"),
      /branchPrefix must be lowercase and end with a slash/,
    );
  });

  it("refuses an engine range that is not >=X.Y.Z", () => {
    refuses((c) => (c.autoclaude = "latest"), /autoclaude must be a range like ">=0\.1\.0"/);
  });

  it("refuses a malformed gate and a repeated gate name", () => {
    refuses((c) => (c.gates = [{ name: "t" }]), /gates\[0\]\.check must be a non-empty command/);
    refuses(
      (c) =>
        (c.gates = [
          { name: "t", check: "a" },
          { name: "t", check: "b" },
        ]),
      /gates\[1\]\.name repeats/,
    );
  });

  it("refuses a red step with an unknown result form", () => {
    refuses((c) => (c.redStep.result = "tap"), /redStep\.result must be one of junit, exit-code/);
  });

  it("validates the later-phase keys now", () => {
    refuses(
      (c) => (c.budget = { claude: { fiveHourPct: 120, weeklyPct: 50 } }),
      /budget\.claude\.fiveHourPct must be a number from 0 to 100/,
    );
    refuses((c) => (c.budget = { gemini: {} }), /unknown key "budget\.gemini"/);
    refuses((c) => (c.triage = { since: "yesterday" }), /triage\.since must be an ISO date/);
    refuses(
      (c) => (c.triage = { maxPerDay: 0 }),
      /triage\.maxPerDay must be a whole number of at least 1/,
    );
    refuses(
      (c) => (c.automerge = { enabled: true, label: "a", categories: [], method: "fast" }),
      /automerge\.method must be one of squash, merge, rebase/,
    );
  });

  it("refuses a malformed label rule", () => {
    refuses(
      (c) => (c.labelRules = [{ when: [], label: "x" }]),
      /labelRules\[0\]\.when must be a non-empty list/,
    );
  });
});
