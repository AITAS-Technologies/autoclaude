/**
 * The `.autoclaude/` project contract. Every engine module reads project facts through
 * `ProjectConfig`; nothing project-specific is hardcoded in the engine.
 */

export type Runtime = "claude" | "codex";

/** How hard a stage is asked to think. */
export const EFFORTS = ["low", "medium", "high", "max"] as const;
export type Effort = (typeof EFFORTS)[number];

export interface StageSpec {
  runtime: Runtime;
  model: string;
  effort: Effort;
  fallback?: Omit<StageSpec, "fallback">;
}

/** The readings the code review fans out to, one reviewer each. */
export const CODE_REVIEW_ANGLES = [
  "criteria",
  "bugs",
  "invariants",
  "history",
  "prior-prs",
  "comments",
  "performance",
  "tests",
  "security",
] as const;
export type CodeReviewAngle = (typeof CODE_REVIEW_ANGLES)[number];

export interface Gate {
  name: string;
  check: string;
  fix?: string;
  when?: string[];
}

export interface ProjectConfig {
  autoclaude: string; // semver range, e.g. ">=0.1.0"
  forge: { remote: string };
  branches: { integration: string; production: string };
  branchPrefix: string;
  humans: string[];
  bootstrap?: string;
  gates: Gate[];
  redStep: {
    testFiles: string[];
    supportFiles: string[];
    exclude: string[];
    run: string;
    result: "junit" | "exit-code";
    install?: { when: string; run: string };
  };
  worktrees: { root: string; copy: string[] };
  stages: {
    triage: StageSpec;
    plan: StageSpec;
    planReview: StageSpec & { scorer: StageSpec };
    implement: StageSpec & { escalated?: StageSpec };
    codeReview: {
      angles: { default: StageSpec } & Partial<Record<CodeReviewAngle, StageSpec>>;
      scorer: StageSpec;
      parallel: number;
    };
  };
  codeReview: { angles: CodeReviewAngle[]; scoreThreshold: number };
  planReview: { scoreThreshold: number };
  queue: { ready: string; priority: string[] };
  labels: {
    working: string;
    blocked: string;
    needsShaping: string;
    fixRound: string;
    reviewRetry: string;
  };
  humanApproval: Array<{ paths: string[]; label: string }>;
  labelRules: Array<{ when: string[]; unless?: string[]; label: string; suppressedBy?: string }>;
  requiredChecks: string[];
  forbiddenPaths: string[];
  policyAdjacentPaths: string[];
  policyAdjacentReason?: string;
  fence: { allow: string[] }; // extra command prefixes a stage may run
  caps: {
    concurrency: { day: number; night: number };
    fixRounds: number;
    reviewRetries: number;
    planRounds: number;
    issuesPerNight: number;
    wallClockMinutesPerStage: number;
    openPullRequests: number;
    staleClaimHours: number;
    maxTurnsPerStage: number;
  };
  schedule: {
    timezone: string;
    profiles: { day: { from: string; to: string }; nightStopsTakingWorkAt: string };
  };
  // accepted and validated now, acted on in later phases:
  budget?: Partial<Record<Runtime, { fiveHourPct: number; weeklyPct: number }>>;
  triage?: { since?: string; optInLabel?: string; maxPerDay?: number; at?: string };
  automerge?: {
    enabled: boolean;
    label: string;
    categories: string[];
    method: "squash" | "merge" | "rebase";
  };
  messages: { footer: string; defuseMentions: boolean }; // footer default "Generated by autoclaude"
}

/** The only top-level keys `config.local.json` may carry: a developer's own, not the project's. */
export const LOCAL_OVERRIDABLE = ["budget", "schedule", "humans", "stages"] as const;
