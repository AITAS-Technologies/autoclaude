/** What the engine writes to GitHub when the project's config names no `messages`. */
export const DEFAULT_MESSAGES: ProjectConfig["messages"] = {
  footer: "Generated by autoclaude",
  defuseMentions: true,
};

/**
 * Every message, quote and uncertain line the engine writes to GitHub is model-written
 * text, and a workflow that triggers on a mention would start a run from inside a pull
 * request body or a review comment. Defusing is the project's to turn off
 * (`messages.defuseMentions`), and its own people (`humans`) stay mentionable.
 */
export function presentText(
  text: string,
  messages: ProjectConfig["messages"] = DEFAULT_MESSAGES,
  humans: string[] = [],
): string {
  return messages.defuseMentions ? defuseMentions(text, humans) : text;
}

/**
 * The labels the engine adds to a pull request from the paths its diff changed — the
 * project's `labelRules` (design section 8.2), which replace the one browser-review
 * special case of the source this was ported from.
 *
 * Decided deterministically, never from a model's judgement: a wrong yes costs a slow
 * job, a wrong no ships an unreviewed screen, and both are too expensive to guess at.
 * A rule fires when
 *   - some changed file matches `when`,
 *   - `unless` does **not** cover the whole diff, and
 *   - its `suppressedBy` label is absent from `current`.
 *
 * `unless` overrides `when` **only when it covers the whole diff**. Applying it per file
 * would drop a real change the moment a test or a changelog entry travelled with it,
 * which is what most pull requests look like.
 *
 * Only ever adds, and never a label that is already there. A human may have applied the
 * label to a diff whose paths do not call for it, and removing it again would undo that
 * decision silently on the next push — publish runs with `--update` every time.
 */
export function labelChanges(
  changed: string[],
  current: string[],
  cfg: Pick<ProjectConfig, "labelRules">,
): { add: string[] } {
  const add: string[] = [];
  for (const rule of cfg.labelRules ?? []) {
    if (!changed.some((f) => matchesAny(f, rule.when))) continue;
    const unless = rule.unless ?? [];
    if (unless.length > 0 && changed.every((f) => matchesAny(f, unless))) continue;
    if (rule.suppressedBy !== undefined && current.includes(rule.suppressedBy)) continue;
    if (current.includes(rule.label) || add.includes(rule.label)) continue;
    add.push(rule.label);
  }
  return { add };
}

/** The diff files that need one `humanApproval` entry's label; only entries the diff touches. */
export interface ApprovalNeeded {
  label: string;
  files: string[];
}

/**
 * Which `humanApproval` entries the diff touches (design section 8.2, defect 6): for each
 * entry, the changed files matching its `paths`. An entry with no matching file is left
 * out. One reading, shared by the pull request body and the merge verdict's check 7.
 */
export function approvalsNeeded(
  changed: string[],
  humanApproval: ProjectConfig["humanApproval"] = [],
): ApprovalNeeded[] {
  return humanApproval
    .map((entry) => ({
      label: entry.label,
      files: changed.filter((f) => matchesAny(f, entry.paths)),
    }))
    .filter((a) => a.files.length > 0);
}

/**
 * Nothing the engine writes to GitHub carries a CI skip marker (plan Global Constraints):
 * the pull request's CI would never start, and a required check that never reports reads
 * as a refusal at the merge verdict.
 */
const SKIP_MARKERS = /\[(?:skip ci|ci skip|no ci|skip actions|actions skip)\]/gi;

export function prTitle(subject: string, issue: number): string {
  const clean = subject.replace(SKIP_MARKERS, " ").replace(/\s+/g, " ").trim();
  return clean.includes(`#${issue}`) ? clean : `${clean} (#${issue})`;
}

/** A finding as the body renders it: the parser's, plus the repeat flag the decision adds. */
type BodyFinding = ReviewFinding & { seenBefore?: boolean };

/**
 * The diff review's findings point at the branch, which the reader can open.
 *
 * A repeat says so. The same rule quoting the same line already stood in the previous
 * round's report, and a reader who has seen it once should not have to read it as new
 * (design, "Fingerprint and evidence, verified rather than trusted").
 */
const atFileAndLine = (f: BodyFinding) =>
  // `findingHead`, the one place rule, position and confidence are formatted — so a
  // finding with no file (`spec/criterion-not-met` is the common one) does not read "at
  // `:0`" here or in the review comment.
  `${findingHead(f)}${f.seenBefore ? " (noted in an earlier round)" : ""}: ${f.message}`;

/**
 * A plan review's finding names the plan file and a line in it, and by the time anyone
 * reads this both are gone: `archivePlanFile` moved the plan into the run archive and
 * Step 3 removed the worktree. A path that does not resolve is worse than no path, and
 * `evidence` — the verbatim line the finding is about, which `findingsAsMarkdown` does
 * render — was being dropped.
 */
const withEvidence = (f: BodyFinding) => {
  const evidence = f.evidence.trim();
  const quoted = evidence ? ` Evidence: \`${evidence.slice(0, 200)}\`` : "";
  return `\`${f.rule}\` (confidence ${f.confidence}): ${f.message}${quoted}`;
};

/** How many fix rounds this change has had, and how many it was allowed. */
export interface FixRounds {
  /** `attempts.fix`, the rounds already spent. */
  fix: number;
  /** `caps.fixRounds`. */
  cap: number;
}

/**
 * Why the open should findings are in a pull request body instead of in another fix round.
 *
 * At the cap is the only way they get here: below it a should finding is a fix round, so
 * that is the sentence the note fixes. The other ending exists so that a body rendered
 * by hand, or one whose caller knows no counters, cannot claim a cap it never reached.
 */
function shouldIntro(rounds: FixRounds | null): string {
  const decides = "A human decides whether they block the merge.";
  if (rounds === null) return decides;
  const spent = `${rounds.fix} fix round${rounds.fix === 1 ? "" : "s"}`;
  const where = rounds.fix >= rounds.cap ? ", the cap" : ` of ${rounds.cap}`;
  return `These remained open after ${spent}${where}. ${decides}`;
}

/**
 * The code review's sections carry what a class costs; the plan review's are all noted,
 * so it uses `TIER_HEADINGS` itself.
 *
 * `reports.ts` owns that list, the one statement of the tier vocabulary, so the maps here,
 * in `decision.ts` and in `post-review.ts` cannot drift into three names for one
 * class. This is the only one that differs from it, by the body's "Should, open".
 */
const CODE_HEADINGS: Record<Tier, string> = { ...TIER_HEADINGS, should: "Should, open" };

/**
 * Every finding the body shows, and whether an earlier round already reported it.
 *
 * `decide`'s own `kept` list: the report's findings **minus what the evidence check
 * withdrew**, in the report's order, each carrying its repeat flag. Those withdrawn are
 * not findings any more, and the Uncertain section lists them with the note saying why.
 *
 * It used to be rebuilt here, by matching the report's findings against the decision's
 * two lists on a key of rule, quote, file and line — a third notion of a finding's
 * identity, correct only while `establish` handed its findings back unchanged.
 *
 * Without a decision every finding stands and none is a repeat: that is what a body
 * rendered by hand gets, and it is the honest answer, because nothing checked anything.
 */
function bodyFindings(review: CodeReviewReport, decision: Decision | null): BodyFinding[] {
  return decision === null ? review.findings : decision.kept;
}

/**
 * One review's section of the body: the banner when the run did not finish, what the
 * review did, and then its findings — or the sentence that says there are none.
 *
 * The shape is the same for both reviews and the wording is not, so the name is a
 * parameter: "the code review did not finish", "No findings remained after the plan
 * review". A missing report says so rather than rendering as "no findings", because that
 * is the shape the defect had: absence and cleanliness must not look alike. A report that
 * stopped before its status line says that too — `parseCodeReviewReport` returns
 * `complete: false` rather than throwing, and reading that as clean is the same
 * conflation.
 *
 * @param middle `lead` is what the section says before its findings and is printed even
 *   when there are none; `findings` is what the empty sentence replaces.
 */
function reviewSection<T extends ReviewReport>(
  name: string,
  review: T | null,
  missing: string,
  middle: (review: T) => { lead: string[]; findings: string[] },
): string[] {
  if (!review) return [missing, ""];
  const { lead, findings } = middle(review);
  return [
    ...(review.complete
      ? []
      : [
          `**The ${name} did not finish.** What follows is what it had written when it stopped, not a verdict.`,
          "",
        ]),
    ...lead,
    ...(findings.length ? findings : [`No findings remained after the ${name}.`, ""]),
  ];
}

/**
 * The code review as the body shows it: what it did, then one section per class, then
 * what it was not sure about (design, "What the pull request shows").
 *
 * All four classes, because until now only the `should` tier was rendered: a `later` item
 * reached nobody, an uncertain one reached nobody, and the lines saying how the review ran
 * existed only in the lead's chat message (design, "Why"). The Must section is here for
 * the one case that gets past the decision gate below — a body rendered by hand — and its
 * own intro says so.
 */
function codeReviewSection(
  review: CodeReviewReport | null,
  rounds: FixRounds | null,
  decision: Decision | null,
): string[] {
  return reviewSection("code review", review, "No code review report was available.", (r) => ({
    // What the review did leads the section: it is what tells a thorough review from a
    // cursory one, and a red step that could not run is published rather than blocked, so
    // the human who merges is the one reader left to act on it. Printed even when nothing
    // was found, which is why it is the lead and not part of the findings.
    lead: reviewAccountAsMarkdown(r),
    findings: [
      ...tierSections(bodyFindings(r, decision), atFileAndLine, {
        headings: CODE_HEADINGS,
        intro: {
          must: "These block; this body should not exist.",
          should: shouldIntro(rounds),
          later: "Noted by the review, deliberately not fixed:",
        },
      }),
      // The reviewer's own lines, what the classification withdrew below the threshold,
      // and what the evidence check withdrew — the last of which only the decision knows.
      ...uncertainSection([
        ...r.uncertain,
        ...(decision?.demoted ?? []).map(
          (f) => f.demotion ?? `${f.rule} — the claim was withdrawn`,
        ),
      ]),
    ],
  }));
}

/**
 * The plan review as the body shows it: the classes that did not block, and what it was
 * unsure about.
 *
 * It has to be rendered here: its report is archived out of the worktree the moment the
 * implement stage is dispatched, so a body built from the implement and review reports
 * alone would leave a whole stage's non-blocking output with neither the implementer — a
 * fresh dispatch carries no findings by design — nor the pull request. It would survive
 * only in `.autoclaude/state/runs/<n>/plan-review-N.md`, which nobody opens, and a finding
 * it made would reach the human reviewer as silence.
 *
 * No Must section: a plan whose review left a must finding open never reached the
 * implement stage, so a must here is a finding that cost a plan round and was then fixed.
 */
function planReviewSection(planReview: ReviewReport | null, problem: string | null): string[] {
  return reviewSection(
    "plan review",
    planReview,
    problem ?? "No plan review report was available.",
    (r) => ({
      lead: [],
      findings: [
        ...tierSections(
          r.findings.filter((f) => f.tier !== "must"),
          withEvidence,
          {
            headings: TIER_HEADINGS,
            // No `must`: the section filters that tier out above, because a plan whose
            // review left a must open never reached the implement stage.
            intro: {
              should: "Raised against the plan and not blocking:",
              later: "Noted by the plan review, deliberately not fixed:",
            },
          },
        ),
        ...uncertainSection(r.uncertain),
      ],
    }),
  );
}

export interface PrBodyOptions {
  /**
   * The `humanApproval` entries the diff touches, from `approvalsNeeded`. Absent or empty
   * leaves the section out: the body says nothing about approval for a diff that needs
   * none.
   */
  approvals?: ApprovalNeeded[];
  /** `cfg.messages`: the footer, and whether mentions are defused. Defaults to `DEFAULT_MESSAGES`. */
  messages?: ProjectConfig["messages"];
  /** `cfg.humans`: the handles whose mention survives defusing. */
  humans?: string[];
  /** The counters behind the open-should sentence; absent leaves the sentence without them. */
  rounds?: FixRounds | null;
  /**
   * What `decide` made of the same report: the claims its evidence check withdrew and the
   * findings an earlier round already carried, neither of which the report itself knows.
   * Absent renders the report exactly as it stands.
   */
  decision?: Decision | null;
}

export function prBody(
  issue: number,
  impl: ImplementReport,
  review: CodeReviewReport | null,
  planReview: ReviewReport | null,
  planReviewProblem: string | null,
  machine: string,
  rebasedOnto: string | null,
  opts: PrBodyOptions = {},
): string {
  const {
    approvals = [],
    messages = DEFAULT_MESSAGES,
    humans = [],
    rounds = null,
    decision = null,
  } = opts;
  const criteria = impl.criteria.map((c) => `- [${c.met ? "x" : " "}] ${c.text}`).join("\n");
  const notDone = impl.observedNotDone.length
    ? impl.observedNotDone.map((l) => `- ${l}`).join("\n")
    : "- nothing noted";
  // The findings, the quotes, the criteria and the implementer's own lines are all
  // model-written, and a workflow that triggers on the mention they may contain would start
  // a run from inside a pull request body. One helper with `post-review.ts`, whose comment
  // carries the same text.
  return presentText(
    [
      `Closes #${issue}`,
      "",
      `<!-- autodev-pr issue="${issue}" machine="${machine}" -->`,
      "Opened by autoclaude after a local review with a fresh context. A human reviews and merges; nothing here merges itself.",
      "",
      "## Acceptance criteria",
      "",
      criteria || "- (the report listed no criteria)",
      "",
      "## Code review",
      "",
      ...codeReviewSection(review, rounds, decision),
      "## Plan review",
      "",
      "_Raised against the plan before any code was written, and not blocking._",
      "",
      ...planReviewSection(planReview, planReviewProblem),
      // One line per `humanApproval` entry the diff matches; nothing, heading included,
      // when none does (design section 8.2, defect 6).
      ...(approvals.length
        ? [
            "## Human approval",
            "",
            ...approvals.map(
              (a) =>
                `This diff touches \`${a.files.join(", ")}\`. It may only be merged by a human, or after a human applies \`${a.label}\`.`,
            ),
            "",
          ]
        : []),
      "## Observed, not done",
      "",
      notDone,
      "",
      rebasedOnto
        ? `_This branch was rebased onto ${rebasedOnto} immediately before the push; the local gates ran before the rebase._`
        : "",
      "",
      messages.footer,
    ]
      // Every section renderer above returns lines, because this filter works on array
      // elements and never sees a `"\n\n"` inside one: a renderer that joined its own
      // output would collapse the very sections it separated.
      .filter((line, i, arr) => !(line === "" && arr[i - 1] === ""))
      .join("\n"),
    messages,
    humans,
  );
}

export interface PublishDeps {
  exec: Exec;
  root: string;
  cfg: ProjectConfig;
  now?: Date;
  /**
   * The forge every `gh` call goes through, carrying `-R <owner>/<repo>`. Absent resolves
   * the repository from `forge.remote`'s URL, after the gates and before the first write.
   */
  forge?: Forge;
}

export type PublishResult =
  | { code: 0; issue: number; pr: number; url?: string; rebased: boolean; pushed: string }
  | { code: 3; issue: number; conflict: string };

/**
 * The whole step as a function, so a test can drive it with a fake runner and a
 * temporary root. Order matters: every
 * input is read and every gate passed before the first command that changes anything
 * outside the worktree.
 */
export function publish(issue: number, update: boolean, deps: PublishDeps): PublishResult {
  const { exec, root, cfg } = deps;
  const now = deps.now ?? new Date();
  const ledger = loadLedger(root);
  const entry = ledger.issues[String(issue)];
  if (!entry) throw new Error(`no ledger entry for issue ${issue}`);
  if (!entry.worktree) {
    throw new Error(
      `issue ${issue}: the ledger entry names no worktree, so there is nothing here to push`,
    );
  }
  // The branch, through the one rule the ledger's branch setter and the rollback apply to
  // the same field. This was `startsWith(cfg.branchPrefix)`, which is every agent branch of
  // every issue: a row naming `agent/91-bar` under issue 9 was pushed and got a pull
  // request opened for it, and a hand-edited or reconciled row is the way that happens
  // (`notIssueBranch` says why the field is free text). The refspec below stops a stored
  // name from choosing its own destination; it does not stop the wrong branch being
  // published. Ahead of the report reads and of every git command this function issues of
  // its own, so a refusal here leaves the worktree and the remote untouched — the one git
  // that may have run by then is the gate's own `check-ref-format`, which reads a name and
  // needs no repository.
  const outside = notIssueBranch(entry.branch, issue, cfg, exec);
  if (outside !== null) {
    throw new Error(
      `issue ${issue}: the ledger names branch "${entry.branch}", and this pushes that branch and opens a pull request for it — ${outside}. Correct the row first: set the entry's \`branch\` for issue ${issue} in .autoclaude/state/ledger.json to a name starting ${branchPrefixFor(issue, cfg)}`,
    );
  }
  if (update && !entry.pr)
    throw new Error(`issue ${issue}: --update without a pull request number in the ledger`);
  const wt = entry.worktree;
  const remote = cfg.forge.remote;
  const base = `${remote}/${cfg.branches.integration}`;
  const gitIn = (args: string[]) => git(args, exec, wt);

  // 1. The inputs. The implement report was archived before the reviewer was dispatched, so it is read from the
  //    archive; the review report is still in the worktree. Both are required: a missing
  //    or unfinished review is not "no findings", it is no review.
  const impl = parseImplementReport(readLatestReport(root, entry, "implement"));
  // The catalogue is the engine's rules plus the project's own `.autoclaude/invariants.md`
  // under `root` (design section 8.1), read once and shared by both reports and the
  // previous archive; the thresholds are the config's.
  const codeOpts = classifyOptions("code-review", { cfg, projectRoot: root });
  const reviewText = readReport(wt, "code-review");
  // Completeness first, as the CLI decides it: a reviewer stopped before it wrote its
  // verdict is an unfinished review, and parsing first would blame the missing field.
  if (!isReportComplete("code-review", reviewText)) {
    throw new Error(
      `issue ${issue}: the review report is not marked complete; refusing to publish an unreviewed diff`,
    );
  }
  const review: CodeReviewReport = parseCodeReviewReport(reviewText, codeOpts);
  // Only a worktree review is ever published, and a worktree always has its issue. The
  // parser accepts `criteria: none` from any review, so this is where it is refused: here
  // it can only mean a review that skipped the criteria.
  if (review.criteriaNone) {
    throw new Error(
      `issue ${issue}: the review says "criteria: none", but a worktree review always has its issue; refusing to publish a review that checked no criteria`,
    );
  }
  // Archived before the implement stage was dispatched, so it is only ever in the
  // archive. Advisory, unlike the two above: a missing one is reported in the body,
  // not thrown, because it must not stop a reviewed diff from reaching a human.
  // Absent and unreadable are different answers, and a bare catch made them the same:
  // truncating a report to 60% makes `parsePlanReviewReport` throw, and the body then said
  // "No plan review report was available." for a report sitting on disk with two findings
  // in it.
  let planReview: ReviewReport | null = null;
  let planReviewProblem: string | null = null;
  try {
    planReview = parsePlanReviewReport(
      readLatestReport(root, entry, "plan-review"),
      classifyOptions("plan-review", { cfg, catalogue: codeOpts.catalogue }),
    );
  } catch (error) {
    const why = error instanceof Error ? error.message : String(error);
    planReviewProblem = /no plan-review report/i.test(why)
      ? null
      : `**The plan review report could not be read**: ${why.slice(0, 300)}`;
  }

  // 2. The decision, asked again here. The orchestrator runs decision.ts and does
  //    what it says; this is defence in depth, the way `criteria: none` is refused twice
  //    (design, "The rounds"). It is the gate that catches a review whose findings are
  //    simply not addressed yet — an open must at the cap belongs on a blocked issue, and
  //    the body it would otherwise get is the one whose Must section says it should not
  //    exist. Before the first command, like every gate above it: nothing outside the
  //    worktree may change on a diff that is not publishable.
  const decision = decide(review, entry.attempts, cfg, {
    stage: "code-review",
    worktree: wt,
    previous: previousReport(root, issue, "code-review", codeOpts),
  });
  if (decision.action !== "publish") {
    throw new Error(
      `issue ${issue}: the review decides \`${decision.action}\` (${decision.reason}); refusing to publish`,
    );
  }

  // 3. Rebase onto the current integration tip, and prove it.
  gitIn(["fetch", remote, cfg.branches.integration, "--quiet"]);
  // The tip the review read: the fetch moves no branch of this worktree, and every gate
  // above it has already run, so nothing has touched HEAD since the report was written.
  // It is half the archive's stamp, and it is also the history the lease below leans on.
  const tipBefore = gitIn(["rev-parse", "HEAD"]).trim();
  const rebase = exec("git", ["rebase", base], { cwd: wt });
  if (rebase.status !== 0) {
    const output = `${rebase.stdout}\n${rebase.stderr}`.trim();
    exec("git", ["rebase", "--abort"], { cwd: wt });
    // git prints CONFLICT lines on stdout; anything else (a dirty tree, a leftover
    // rebase directory) is an error of its own, not a conflict.
    if (/CONFLICT/.test(output)) return { code: 3, issue, conflict: output };
    throw new Error(`issue ${issue}: git rebase ${base} failed:\n${output}`);
  }
  const head = gitIn(["rev-parse", "HEAD"]).trim();
  const rebased = head !== tipBefore;
  if (!isRebasedOnto(base, "HEAD", (args) => exec("git", args, { cwd: wt }))) {
    throw new Error(
      `issue ${issue}: still not rebased onto ${base} after rebasing; refusing to push`,
    );
  }

  // 4. The one point every diff passes through, so the one place a prose rule becomes
  //    a gate: nothing under forbiddenPaths or policyAdjacentPaths leaves the worktree.
  //    --no-renames lists both sides of a rename, so a file moved out of a guarded
  //    location is still seen under its guarded name.
  const changed = gitIn(["diff", "--name-only", "--no-renames", `${base}...HEAD`])
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  const fenced = [...cfg.forbiddenPaths, ...cfg.policyAdjacentPaths];
  const forbidden = changed.filter((f) => matchesAny(f, fenced));
  if (forbidden.length) {
    throw new Error(
      `issue ${issue}: the diff touches forbidden or policy-adjacent paths, refusing to push: ${forbidden.join(", ")}`,
    );
  }

  // 5. Push. The remote branch holds nothing (first push), what this machine pushed last
  //    (pushedSha), or a commit from elsewhere. A lease names the one commit the push may
  //    replace; a bare --force-with-lease compares against the tracking ref, which any
  //    fetch moves. Without a recorded sha, git's own proof decides:
  //    the remote head must already be in the history this worktree had before the
  //    rebase, otherwise the branch carries a commit nobody here has seen, a human's fix
  //    or an earlier attempt, and the push is refused. A retry after a
  //    partial success has its sha recorded and takes the lease path whatever the flag
  //    says.
  //
  //    Both pushes name a full refspec, `refs/heads/<b>:refs/heads/<b>`, so the stored
  //    name can never name a different destination. `entry.branch` is free text with three
  //    writers, and a colon makes it a refspec: `git push <remote> agent/9-x:develop` sends
  //    this worktree's branch — rebased onto <remote>/develop just above — to remote
  //    `develop` as a fast-forward, no pull request, no force, and `:main` reaches
  //    production. The `--branch` gate refuses a colon now; this is the second fence, in
  //    the one place that pushes.
  const refspec = `refs/heads/${entry.branch}:refs/heads/${entry.branch}`;
  const remoteHead =
    gitIn(["ls-remote", "--heads", remote, entry.branch]).trim().split(/\s+/)[0] || null;
  // The repository every `gh` call below names, resolved before the first write so a
  // remote that is not a GitHub repository stops the step with nothing pushed.
  const forge = deps.forge ?? new Forge(resolveRepo(remote, wt, exec), exec);
  if (remoteHead === null) {
    gitIn(["push", "-u", remote, refspec]);
  } else {
    if (entry.pushedSha === null) {
      const known =
        exec("git", ["merge-base", "--is-ancestor", remoteHead, tipBefore], { cwd: wt }).status ===
        0;
      if (!known) {
        throw new Error(
          `issue ${issue}: ${remote}/${entry.branch} is at ${remoteHead}, a commit this worktree never had (a human's push, or an earlier attempt's branch); refusing to force over it. Clear the branch with \`autoclaude rollback ${issue}\`, or lease on it by hand.`,
        );
      }
    }
    const lease = entry.pushedSha ?? remoteHead;
    gitIn([
      "push",
      `--force-with-lease=refs/heads/${entry.branch}:${lease}`,
      "-u",
      remote,
      refspec,
    ]);
  }
  // Every write from here on re-reads the file under the lock: the rebase and the push
  // above took time, and another process may have written in between.
  // The state written is the one found there, not the one in the snapshot taken before
  // the push; passing the stale value would force it back over whatever moved.
  const keepState = (l: Ledger) => l.issues[String(issue)]?.state ?? entry.state;
  /**
   * One transition, in the ledger and in the issue's events log.
   *
   * The log line goes through `appendNoteBestEffort` and `transitionText`, the pair
   * `ledgerCli("set")` uses, inside the same callback and before `saveLedger` renders
   * `status.md` — so the Running section it writes already carries this line. Every
   * transition this script made used to reach the ledger and not the log, so a human
   * following a run saw `code-reviewing` and then a pull request, with the push and the
   * creation in between missing. Best-effort,
   * because by this point the push has happened and a line nothing reads back for a
   * decision must not fail a transition that is already true.
   */
  const record = (
    to: (l: Ledger) => IssueState,
    patch: Partial<Omit<LedgerEntry, "issue" | "state">> & { note?: string },
  ): void => {
    updateLedger(
      root,
      (l) => {
        const before = l.issues[String(issue)];
        const state = to(l);
        const written = transition(l, issue, state, patch, now);
        appendNoteBestEffort(
          root,
          issue,
          transitionText({ from: before?.state ?? null, to: state, note: patch.note ?? null }),
          written.stage?.stage ?? null,
          now,
        );
        return written;
      },
      now,
    );
  };
  record(keepState, { pushedSha: head, note: `pushed ${head} to ${entry.branch}` });

  // 6. The pull request: created only while the ledger has no number for it, and its body
  //    rewritten on every push after that. The number goes to the ledger the moment it
  //    exists, so a failure after this point cannot leave a retry trying to create it
  //    twice.
  const baseSha = rebased ? gitIn(["rev-parse", "--short", base]).trim() : null;
  const body = prBody(issue, impl, review, planReview, planReviewProblem, ledger.machine, baseSha, {
    approvals: approvalsNeeded(changed, cfg.humanApproval),
    messages: cfg.messages,
    humans: cfg.humans,
    rounds: { fix: entry.attempts.fix, cap: cfg.caps.fixRounds },
    decision,
  });
  let pr = entry.pr as number;
  let url: string | undefined;
  if (entry.pr === null) {
    const subject = gitIn(["log", "-1", "--format=%s"]).trim();
    const created = forge.createPr({
      base: cfg.branches.integration,
      head: entry.branch,
      title: prTitle(subject, issue),
      body,
    });
    pr = created.number;
    url = created.url;
    const opened = pr;
    record(keepState, { pr: opened, note: `pull request #${opened} opened` });
  } else if (update) {
    // The body written at creation used to stay put through every fix round, so a human
    // read the first review's sections against the third push's diff. The cost of
    // rewriting it is stated in the design and accepted: a human's edit to an agent's
    // pull request body is lost on the next push.
    //
    // Gated on the flag and not merely on "a pull request exists", which is what this
    // was: `publish.ts <issue>` typed by hand on an issue that already had one rewrote
    // its body against this file's own header (`/code-review` on the review-tiers
    // branch). The orchestrator passes `--update` exactly when the ledger has a number,
    // so nothing about an orchestrated run changes.
    forge.editPrBody(pr, body);
  }

  // 7. Apply the project's label rules to the pull request. Deterministic, from the paths
  //    this diff changed (design section 8.2): the label is the only channel a downstream
  //    workflow reads. The labels of the *pull request* are what such a workflow gates on,
  //    not the issue's, so this cannot go through the issue labels the orchestrator uses.
  const labels = labelChanges(
    changed,
    forge.viewPr(pr).labels.map((l) => l.name),
    cfg,
  );
  if (labels.add.length) forge.editPrLabels(pr, { add: labels.add });

  archiveReport(root, entry, "implement");
  // The stamp `can-merge`'s checks 3 and 6 read back: the sha the review was read at, the
  // sha this push sent, and the decision that was acted on. Here because this is the one
  // place that holds all three — not from a `git rev-parse` inside `archiveReport`, whose
  // callers run in directories that are not repositories, and not from the report block,
  // which is model-written and therefore a claim (design, "`can-merge.ts`: checks 3 and 6
  // become real").
  //
  // The counts are of `decision.kept`, the findings that stood: check 3 used to re-derive
  // them from the archived text, so a must the evidence check withdrew was still a must
  // there and this pull request could never be merged, however correct the publish was.
  const open = findingsByTier(decision.kept);
  archiveReport(
    root,
    entry,
    "code-review",
    // the ledger's writer, beside the reader `can-merge.ts` uses: the seven keys were
    // spelled as literals here and read back as seven more there, two lists that could
    // drift apart with nothing to say they had.
    decisionStamp(tipBefore, head, {
      action: decision.action,
      must: open.must.length,
      should: open.should.length,
      later: open.later.length,
      withdrawn: decision.demoted.length,
    }),
  );
  record(() => "pr-open", { pr, note: entry.pr !== null ? "fix round pushed" : undefined });
  return { code: 0, issue, pr, url, rebased, pushed: head };
}
