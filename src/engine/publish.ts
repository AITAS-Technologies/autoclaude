/**
 * Push a reviewed worktree and open its pull request, or push a fix round to an
 * existing one.
 *
 * Library half; the verb that wraps it is built later and its exit-code contract is
 * recorded here for it (`publish <issue> [--update]`):
 *   exit 0  pushed — and the pull request opened when the ledger holds no number for it,
 *           or its body rewritten when `--update` says to. Without the flag an existing
 *           pull request keeps the body it has
 *   exit 3  the rebase onto the integration branch conflicted; nothing was pushed
 *   exit 1  anything else, the review's own decision included
 * The verb prints the result as one JSON line on stdout, the conflict's git output on
 * stderr, and parses its issue number with `issueArg`.
 *
 * Why a step of the engine and not `gh pr create` typed by the orchestrator: the rebase
 * hook checks HEAD in the directory it runs in, and the orchestrator stands in the main
 * directory on the integration branch, where that test passes trivially. The rule "every
 * pull request is rebased onto the current integration branch before it opens" (design,
 * section 7) is therefore enforced here, on the worktree, through the same isRebasedOnto
 * the hook and the merge verdict use.
 *
 * It also asks `decide` what the review it just read comes to, and publishes nothing
 * unless the answer is `publish`. The orchestrator asks the same question one step
 * earlier; this is the defence in depth the design asks for, in the place that holds the
 * git commands.
 */

